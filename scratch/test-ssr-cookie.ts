import { createServerClient } from "@supabase/ssr";
import { createClient } from "@supabase/supabase-js";
import { loadLocalEnv, requireEnv } from "../scripts/lib/load-env";

loadLocalEnv();
const url = requireEnv("NEXT_PUBLIC_SUPABASE_URL");
const anonKey = requireEnv("NEXT_PUBLIC_SUPABASE_ANON_KEY");

async function main() {
  const client = createClient(url, anonKey, { auth: { persistSession: false } });
  const devTestEmail = "test-verified-dev@betterclinic.app";
  const devPassword = "DevTestPassword123!";

  const { data } = await client.auth.signInWithPassword({
    email: devTestEmail,
    password: devPassword,
  });

  if (!data?.session) {
    console.error("Sign in failed");
    process.exit(1);
  }

  const cookieMap = new Map<string, string>();
  const ssrClient = createServerClient(url, anonKey, {
    cookies: {
      getAll() {
        return Array.from(cookieMap.entries()).map(([name, value]) => ({ name, value }));
      },
      setAll(cookiesToSet: { name: string; value: string }[]) {
        cookiesToSet.forEach(({ name, value }) => cookieMap.set(name, value));
      },
    },
  });

  // Set the session into the SSR client
  await ssrClient.auth.setSession({
    access_token: data.session.access_token,
    refresh_token: data.session.refresh_token,
  });

  console.log("Cookies generated by @supabase/ssr:");
  Array.from(cookieMap.entries()).forEach(([k, v]) => {
    console.log(`  ${k}: ${v.slice(0, 30)}...`);
  });

  const cookieHeader = Array.from(cookieMap.entries())
    .map(([k, v]) => `${k}=${encodeURIComponent(v)}`)
    .join("; ");

  const res = await fetch("http://localhost:3000/dev", {
    headers: {
      Cookie: cookieHeader,
    },
  });

  console.log(`HTTP Status from /dev: ${res.status}`);
  if (res.status === 200) {
    console.log("SUCCESS! /dev returned HTTP 200 for allowlisted developer!");
  } else {
    console.log("Status:", res.status);
  }

  process.exit(0);
}

main().catch(console.error);
