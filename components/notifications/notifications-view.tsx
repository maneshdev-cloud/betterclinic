import Link from "next/link";
import { BellOff } from "lucide-react";
import { PageHeader } from "@/components/shared/page-header";
import { Pagination } from "@/components/shared/pagination";
import { EmptyState } from "@/components/shared/empty-state";
import { MarkAllReadButton, MarkReadButton } from "@/components/notifications/mark-read-buttons";
import { Card, CardContent } from "@/components/ui/card";
import { createClient } from "@/lib/supabase/server";
import { listNotifications, getUnreadCount } from "@/services/notifications/service";
import { searchParamsToObject, buildQueryString } from "@/lib/search-params";
import { cn, formatDateTime } from "@/lib/utils";
import type { Notification } from "@/lib/types/database";

/**
 * Full notifications page content, shared by every role area
 * (/patient/notifications, /doctor/notifications, …).
 */
export async function NotificationsView({
  userId,
  basePath,
  searchParams,
}: {
  userId: string;
  basePath: string;
  searchParams: Record<string, string | string[] | undefined>;
}) {
  const params = searchParamsToObject(searchParams);
  const unreadOnly = params.filter === "unread";
  const page = Math.max(1, Number(params.page) || 1);

  const supabase = await createClient();
  const [result, unreadCount] = await Promise.all([
    listNotifications(supabase, userId, page, unreadOnly),
    getUnreadCount(supabase, userId),
  ]);

  const buildHref = (nextFilter: boolean, nextPage: number) =>
    `${basePath}${buildQueryString({
      filter: nextFilter ? "unread" : undefined,
      page: nextPage === 1 ? undefined : nextPage,
    })}`;

  return (
    <div className="page-container space-y-6 py-8">
      <PageHeader
        title="Notifications"
        description="Booking confirmations, queue calls, prescriptions, follow-ups and reminders — generated by real events only."
        actions={<MarkAllReadButton disabled={unreadCount === 0} />}
      />

      <div className="flex w-full max-w-xs rounded-lg border bg-muted/40 p-1" role="tablist" aria-label="Notification filter">
        {[
          { key: false, label: `All` },
          { key: true, label: `Unread (${unreadCount})` },
        ].map((tab) => (
          <Link
            key={String(tab.key)}
            role="tab"
            aria-selected={unreadOnly === tab.key}
            href={buildHref(tab.key, 1)}
            className={cn(
              "flex-1 rounded-md px-3 py-1.5 text-center text-sm font-medium transition-colors",
              unreadOnly === tab.key
                ? "bg-background text-foreground shadow-sm"
                : "text-muted-foreground hover:text-foreground"
            )}
          >
            {tab.label}
          </Link>
        ))}
      </div>

      {result.items.length === 0 ? (
        <EmptyState
          icon={BellOff}
          title={unreadOnly ? "Nothing unread" : "No notifications yet"}
          description="Notifications appear when you book, get confirmed, are called in the queue, receive prescriptions and more."
        />
      ) : (
        <div className="space-y-2">
          {result.items.map((notification: Notification) => (
            <Card key={notification.id} className={cn(!notification.is_read && "border-primary/40")}>
              <CardContent className="flex items-start justify-between gap-3 p-4">
                <div className="min-w-0">
                  <p className={cn("text-sm", notification.is_read ? "font-normal" : "font-semibold")}>
                    {notification.title}
                    {!notification.is_read ? (
                      <span className="ml-2 inline-block h-2 w-2 rounded-full bg-red-600 align-middle" aria-label="Unread" />
                    ) : null}
                  </p>
                  <p className="mt-0.5 text-sm text-muted-foreground">{notification.body}</p>
                  <p className="mt-1 text-xs text-muted-foreground">{formatDateTime(notification.created_at)}</p>
                </div>
                {!notification.is_read ? <MarkReadButton notificationId={notification.id} /> : null}
              </CardContent>
            </Card>
          ))}
        </div>
      )}

      <Pagination
        page={result.page}
        totalPages={result.totalPages}
        buildHref={(nextPage) => buildHref(unreadOnly, nextPage)}
      />
    </div>
  );
}
